//! Device reports and the reply path (#10): DA, DSR, XTVERSION, DECRQM,
//! DECRQSS, XTWINOPS and the title stack.
//!
//! Expected behaviour comes from `tests/fixtures/reports_spec.txt`, whose
//! header cites xterm's source, ctlseqs, DEC's manuals, kitty and the
//! programs that send each query, and lists the decisions (D-ID, D-DA1, …)
//! the rows encode. The fixture has its own layout, read here:
//!
//! - `### <id>` starts a row; `size: RxC` gives the terminal size;
//! - `step: feed <payload>` feeds the payload (everything after `feed `,
//!   with `\e` for ESC and the escapes of [`common::decode`]); `step: feed
//!   (N times) <payload>` feeds it N times (the rows "Generated by the
//!   test");
//! - `step: set cell_px <W>x<H>` calls [`Terminal::set_cell_pixels`];
//! - `step: set title <text>` feeds `OSC 2 ; text ST` and drops what it
//!   requested: the title is the one the terminal already emitted;
//! - `reply: <bytes>|none` checks the [`Request::Reply`] bytes queued since
//!   the previous `reply:` line, concatenated in order (`none`: no reply at
//!   all); `<VERSION>` is this crate's version, `<PV>` is [`DA2_PV`];
//! - `requests: [..]` checks the other requests since the previous
//!   `requests:` line: `SetTitle("..")`, `Bell` and `Resize(r,c)`;
//! - `screen:` (`>` lines) and `cursor: (row,col)` check the screen after the
//!   last step, rendered by [`common::render_screen`];
//! - `cite:`, `note:` and `flags:` are not checked.
//!
//! [`every_row`] runs every row whole, byte by byte and split in two at
//! every offset of every feed step, and expects the same replies each time.
//! The generated rows (a million repetitions) run whole with all their
//! repetitions, and byte by byte and split at every offset of their first
//! repetition with [`CHUNKED_REPEAT`] of them: the input is periodic, so a
//! split in any later repetition leaves the parser where the same split in
//! the first does.

#[allow(dead_code)] // Shared harness: not every helper is used here.
mod common;

use common::{decode, render_screen};
use tessera_grid::Point;
use tessera_term::{DA2_PV, Request, Terminal};

const FIXTURE: &str = include_str!("fixtures/reports_spec.txt");
const FIXTURE_NAME: &str = "fixtures/reports_spec.txt";

/// Repetitions of a generated row's step when it is not fed whole (see the
/// module documentation); enough to fill the title stack many times over.
const CHUNKED_REPEAT: usize = 1_000;

/// One line of a row that does something, in fixture order.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Item {
    /// `step: feed`: the bytes, fed `repeat` times.
    Feed { bytes: Vec<u8>, repeat: usize },
    /// `step: set cell_px`.
    CellPx(u16, u16),
    /// `step: set title`.
    Title(String),
    /// `reply:`: the expected reply bytes, `None` for `none`.
    Reply(Option<Vec<u8>>),
    /// `requests:`.
    Requests(Vec<Request>),
}

/// One row of the fixture.
#[derive(Debug, Clone)]
struct Row {
    id: String,
    rows: u16,
    cols: u16,
    items: Vec<Item>,
    screen: Option<String>,
    cursor: Option<Point>,
}

impl Row {
    fn generated(&self) -> bool {
        self.items
            .iter()
            .any(|item| matches!(item, Item::Feed { repeat, .. } if *repeat > 1))
    }
}

/// Replaces the fixture's `\e` with `\x1b`, leaving `\\` alone, then
/// decodes the other escapes with [`common::decode`].
fn decode_payload(text: &str) -> Vec<u8> {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars();
    while let Some(ch) = chars.next() {
        if ch != '\\' {
            out.push(ch);
            continue;
        }
        match chars.next() {
            Some('e') => out.push_str("\\x1b"),
            Some(next) => {
                out.push('\\');
                out.push(next);
            }
            None => out.push('\\'),
        }
    }
    decode(&out)
}

/// A `reply:` value with its placeholders filled in.
fn parse_reply(text: &str) -> Option<Vec<u8>> {
    if text.trim() == "none" {
        return None;
    }
    let text = text
        .replace("<VERSION>", env!("CARGO_PKG_VERSION"))
        .replace("<PV>", &DA2_PV.to_string());
    Some(decode_payload(&text))
}

/// A `requests:` value: `[]` or a comma-separated list of `Bell`,
/// `SetTitle("..")` and `Resize(r,c)`.
fn parse_requests(text: &str) -> Vec<Request> {
    let inner = text
        .trim()
        .strip_prefix('[')
        .and_then(|t| t.strip_suffix(']'))
        .unwrap_or_else(|| panic!("requests `{text}`: expected `[..]`"));
    let mut requests = Vec::new();
    let mut rest = inner.trim();
    while !rest.is_empty() {
        if let Some(after) = rest.strip_prefix("SetTitle(\"") {
            let end = after
                .find("\")")
                .unwrap_or_else(|| panic!("unterminated SetTitle in `{text}`"));
            let title = String::from_utf8(decode_payload(&after[..end])).expect("UTF-8 title");
            requests.push(Request::SetTitle(title));
            rest = &after[end + 2..];
        } else if let Some(after) = rest.strip_prefix("Bell") {
            requests.push(Request::Bell);
            rest = after;
        } else if let Some(after) = rest.strip_prefix("Resize(") {
            let end = after.find(')').expect("unterminated Resize");
            let (rows, cols) = after[..end].split_once(',').expect("Resize(r,c)");
            requests.push(Request::Resize {
                rows: rows.trim().parse().expect("rows"),
                cols: cols.trim().parse().expect("cols"),
            });
            rest = &after[end + 1..];
        } else {
            panic!("unknown request at `{rest}` in `{text}`");
        }
        rest = rest
            .trim_start()
            .strip_prefix(',')
            .unwrap_or(rest)
            .trim_start();
    }
    requests
}

/// `step:` lines.
fn parse_step(text: &str) -> Item {
    if let Some(payload) = text.strip_prefix("feed ") {
        if let Some(rest) = payload.strip_prefix('(') {
            let (count, payload) = rest
                .split_once(" times) ")
                .unwrap_or_else(|| panic!("`feed {payload}`: expected `(N times) bytes`"));
            let repeat = count.replace(',', "").parse().expect("repeat count");
            return Item::Feed {
                bytes: decode_payload(payload),
                repeat,
            };
        }
        Item::Feed {
            bytes: decode_payload(payload),
            repeat: 1,
        }
    } else if let Some(size) = text.strip_prefix("set cell_px ") {
        let (width, height) = size.trim().split_once('x').expect("cell_px WxH");
        Item::CellPx(
            width.parse().expect("width"),
            height.parse().expect("height"),
        )
    } else if let Some(title) = text.strip_prefix("set title ") {
        Item::Title(title.to_owned())
    } else {
        panic!("unknown step `{text}`");
    }
}

fn parse_point(text: &str) -> Point {
    let (row, col) = text
        .trim()
        .strip_prefix('(')
        .and_then(|t| t.strip_suffix(')'))
        .and_then(|t| t.split_once(','))
        .unwrap_or_else(|| panic!("cursor `{text}`: expected `(row,col)`"));
    Point::new(row.parse().expect("row"), col.parse().expect("col"))
}

fn parse_row(id: String, lines: &[&str]) -> Row {
    let mut row = Row {
        id,
        rows: 0,
        cols: 0,
        items: Vec::new(),
        screen: None,
        cursor: None,
    };
    let mut lines = lines.iter().peekable();
    while let Some(line) = lines.next() {
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, value) = line
            .split_once(':')
            .unwrap_or_else(|| panic!("{}: unexpected line `{line}`", row.id));
        let value = value.strip_prefix(' ').unwrap_or(value);
        match key {
            "size" => {
                let (rows, cols) = value.trim().split_once('x').expect("size RxC");
                row.rows = rows.parse().expect("rows");
                row.cols = cols.parse().expect("cols");
            }
            "step" => row.items.push(parse_step(value)),
            "reply" => row.items.push(Item::Reply(parse_reply(value))),
            "requests" => row.items.push(Item::Requests(parse_requests(value))),
            "screen" => {
                let mut screen = String::new();
                while let Some(text) = lines.peek().and_then(|l| l.strip_prefix('>')) {
                    screen.push_str(text);
                    screen.push('\n');
                    lines.next();
                }
                row.screen = Some(screen);
            }
            "cursor" => row.cursor = Some(parse_point(value)),
            "cite" | "note" | "flags" => {}
            other => panic!("{}: unknown key `{other}`", row.id),
        }
    }
    assert!(row.rows > 0 && row.cols > 0, "{}: no size", row.id);
    row
}

fn rows() -> Vec<Row> {
    let mut raw: Vec<(String, Vec<&str>)> = Vec::new();
    for line in FIXTURE.lines() {
        if let Some(id) = line.strip_prefix("### ") {
            raw.push((id.trim().to_owned(), Vec::new()));
        } else if let Some((_, lines)) = raw.last_mut() {
            lines.push(line);
        }
    }
    raw.into_iter()
        .map(|(id, lines)| parse_row(id, &lines))
        .collect()
}

/// How a row's feed steps reach [`Terminal::advance`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Chunking {
    /// Each feed step in one call.
    Whole,
    /// One byte per call (the first repetition only for generated rows).
    Bytewise,
    /// Feed step `step` in two calls, split after `at` bytes of its first
    /// repetition; every other step whole.
    Split { step: usize, at: usize },
}

/// Replies and other requests collected while running a row.
#[derive(Default)]
struct Collected {
    replies: Vec<Vec<u8>>,
    others: Vec<Request>,
}

impl Collected {
    fn take(&mut self, term: &mut Terminal) {
        for request in term.take_requests() {
            match request {
                Request::Reply(bytes) => self.replies.push(bytes),
                other => self.others.push(other),
            }
        }
    }
}

fn feed(term: &mut Terminal, bytes: &[u8], repeat: usize, index: usize, chunking: Chunking) {
    let mut first = bytes;
    match chunking {
        Chunking::Bytewise => {
            for byte in bytes {
                term.advance(std::slice::from_ref(byte));
            }
            first = &[];
        }
        Chunking::Split { step, at } if step == index => {
            term.advance(&bytes[..at]);
            first = &bytes[at..];
        }
        Chunking::Whole | Chunking::Split { .. } => {}
    }
    term.advance(first);
    if repeat > 1 {
        term.advance(&bytes.repeat(repeat - 1));
    }
}

/// Runs `row` with `chunking` and returns one message per mismatch.
fn check_row(row: &Row, chunking: Chunking) -> Vec<String> {
    let mut errors = Vec::new();
    let mut fail = |what: String| errors.push(format!("{} [{chunking:?}]: {what}", row.id));
    let mut term = Terminal::new(row.rows, row.cols);
    let mut got = Collected::default();
    for (index, item) in row.items.iter().enumerate() {
        match item {
            Item::Feed { bytes, repeat } => {
                let repeat = if chunking == Chunking::Whole {
                    *repeat
                } else {
                    (*repeat).min(CHUNKED_REPEAT)
                };
                feed(&mut term, bytes, repeat, index, chunking);
                got.take(&mut term);
            }
            Item::CellPx(width, height) => term.set_cell_pixels(*width, *height),
            Item::Title(title) => {
                term.advance(format!("\x1b]2;{title}\x1b\\").as_bytes());
                // Already emitted: neither checked nor counted.
                drop(term.take_requests());
            }
            Item::Reply(want) => {
                let replies = std::mem::take(&mut got.replies);
                let concat = replies.concat();
                let ok = match want {
                    None => replies.is_empty(),
                    Some(want) => concat == *want,
                };
                if !ok {
                    fail(format!(
                        "reply {:?} != {:?}",
                        String::from_utf8_lossy(&concat),
                        want.as_deref().map(String::from_utf8_lossy)
                    ));
                }
            }
            Item::Requests(want) => {
                let others = std::mem::take(&mut got.others);
                if others != *want {
                    fail(format!("requests {others:?} != {want:?}"));
                }
            }
        }
    }
    if let Some(screen) = &row.screen {
        let shown = render_screen(&term);
        if shown != *screen {
            fail(format!("screen\n{shown}!=\n{screen}"));
        }
    }
    if let Some(cursor) = row.cursor
        && term.grid().cursor() != cursor
    {
        fail(format!("cursor {:?} != {cursor:?}", term.grid().cursor()));
    }
    errors.extend(generated_extras(row, &mut term, &got, chunking));
    errors
}

/// The checks the generated rows' notes describe beyond their keys.
fn generated_extras(
    row: &Row,
    term: &mut Terminal,
    got: &Collected,
    chunking: Chunking,
) -> Vec<String> {
    let mut errors = Vec::new();
    let id = row.id.split('_').next().unwrap_or_default();
    match id {
        // "depth 10 bounds memory": eleven pops find ten (empty) titles.
        "TS14" => {
            term.advance(&b"\x1b[23;2t".repeat(11));
            let pops = term.take_requests();
            let want = vec![Request::SetTitle(String::new()); 10];
            if pops != want {
                errors.push(format!(
                    "{id} [{chunking:?}]: {} pops after the flood, want 10",
                    pops.len()
                ));
            }
        }
        // 1,000,000 replies (fed whole), the first and last as for one
        // query.
        "RP09" => {
            let n = got.replies.len();
            let want = if chunking == Chunking::Whole {
                1_000_000
            } else {
                CHUNKED_REPEAT
            };
            let all = got.replies.iter().all(|reply| reply == b"\x1b[1;1R");
            if n != want || !all {
                errors.push(format!(
                    "{id} [{chunking:?}]: {n} replies, all CPR 1;1: {all}"
                ));
            }
        }
        _ => {}
    }
    errors
}

/// Every chunking `row` runs with.
fn chunkings(row: &Row) -> Vec<Chunking> {
    let mut all = vec![Chunking::Whole, Chunking::Bytewise];
    for (step, item) in row.items.iter().enumerate() {
        if let Item::Feed { bytes, .. } = item {
            all.extend((1..bytes.len()).map(|at| Chunking::Split { step, at }));
        }
    }
    all
}

/// Every row of the fixture, whole, byte by byte and at every two-way
/// split, through [`common::check_table`]: the rows run must be the
/// fixture's `###` rows, generated rows included.
#[test]
fn every_row() {
    let rows = rows();
    let headings = FIXTURE.lines().filter(|l| l.starts_with("### ")).count();
    assert_eq!(headings, 196, "rows in the fixture");
    let generated: Vec<&str> = rows
        .iter()
        .filter(|row| row.generated())
        .map(|row| row.id.as_str())
        .collect();
    assert_eq!(generated.len(), 2, "generated rows: {generated:?}");
    common::check_table(
        FIXTURE_NAME,
        headings,
        rows.iter().map(|row| (row.id.clone(), row)),
        |row| {
            let errors: Vec<String> = chunkings(row)
                .into_iter()
                .flat_map(|chunking| check_row(row, chunking))
                .collect();
            // The first few say why; the count says how often.
            let shown: Vec<&str> = errors.iter().take(4).map(String::as_str).collect();
            assert!(
                errors.is_empty(),
                "{} mismatches, the first:\n{}",
                errors.len(),
                shown.join("\n")
            );
        },
    );
}

/// vim's real `set title` output (vim 9.1, `vim -u NONE -c 'set title'
/// notes.txt` then `:q`, recorded through a PTY, TERM=xterm-256color,
/// drawing sequences trimmed): it pushes the title with `22;2t` and
/// `22;1t`, sets its own, and on exit pops twice, pushes and pops again.
/// The title before vim is what the host shows afterwards (#181 item 4).
#[test]
fn quitting_vim_restores_the_title_before_it() {
    const VIM: &[u8] = b"\x1b[?1049h\x1b[>4;2m\x1b[?1h\x1b=\x1b[?2004h\x1b[?1004h\x1b[1;24r\
\x1b[?12h\x1b[?12l\x1b[22;2t\x1b[22;1t\x1b[27m\x1b[23m\x1b[29m\x1b[m\x1b[H\x1b[2J\x1b[?25l\
\x1b[24;1H\"notes.txt\" [New]\x1b]2;notes.txt (/tmp) - VIM\x07\x1b[m\x1b[1;1H\x1b[?25h\
\x1b[24;1H\x1b[?2004l\x1b[>4;m\x1b]2;Thanks for flying Vim\x07\x1b[23;2t\x1b[23;1t\
\x1b[22;2t\x1b[22;1t\x1b[23;2t\x1b[23;1t\x1b[24;1H\x1b[K\x1b[24;1H\x1b[?1004l\x1b[?2004l\
\x1b[?1l\x1b>\x1b[?1049l\x1b[>4;m";
    let mut term = Terminal::new(24, 80);
    term.advance(b"\x1b]2;~/src - zsh\x1b\\");
    drop(term.take_requests());
    term.advance(VIM);
    let titles: Vec<Request> = term
        .take_requests()
        .into_iter()
        .filter(|r| matches!(r, Request::SetTitle(_)))
        .collect();
    let title = |t: &str| Request::SetTitle(t.to_owned());
    assert_eq!(
        titles,
        [
            title("notes.txt (/tmp) - VIM"),
            title("Thanks for flying Vim"),
            title("~/src - zsh"),
            title("~/src - zsh"),
        ]
    );
}

/// The accepted risk of ADR 0024: the parser reports the flags-zero reply
/// form `CSI ? 0 u` like the query `CSI ? u`, so both are answered. When
/// `tessera-vt` learns to tell them apart, this test fails and KT07 and
/// RP10 can take `CSI ? 0 u` back.
#[test]
fn the_flags_zero_reply_form_is_answered_like_the_query() {
    let mut term = Terminal::new(24, 80);
    term.advance(b"\x1b[?u\x1b[?0u");
    let reply = Request::Reply(b"\x1b[?0u".to_vec());
    assert_eq!(term.take_requests(), [reply.clone(), reply]);
}

/// No reply ever carries an 8-bit C1 control, whatever DECSCL selected
/// (#96 owns 8-bit replies).
#[test]
fn replies_stay_7bit_after_decscl_selects_8bit() {
    let queries: &[u8] = b"\x1b[c\x1b[>c\x1b[=c\x1b[>q\x1b[5n\x1b[6n\x1b[?6n\x1b[?26n\x1b[4$p\
\x1b[?25$p\x1b[?u\x1bP$qm\x1b\\\x1bP$q\"p\x1b\\\x1b[18t";
    // Level 2 has no DA3.
    for (decscl, count) in [
        (&b"\x1b[64;0\"p"[..], 14),
        (b"\x1b[65;2\"p", 14),
        (b"\x1b[62\"p", 13),
    ] {
        let mut term = Terminal::new(24, 80);
        term.advance(decscl);
        assert!(term.c1_8bit_replies());
        term.advance(queries);
        let replies: Vec<Vec<u8>> = term
            .take_requests()
            .into_iter()
            .filter_map(|r| match r {
                Request::Reply(bytes) => Some(bytes),
                _ => None,
            })
            .collect();
        assert_eq!(replies.len(), count, "{decscl:?}");
        for reply in replies {
            assert!(
                reply.iter().all(|&b| b < 0x80) && reply.starts_with(b"\x1b"),
                "{decscl:?}: {reply:?}"
            );
        }
    }
}
