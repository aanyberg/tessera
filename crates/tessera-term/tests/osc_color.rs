/// The quickest of three runs of `f`.
fn best_of_three(mut f: impl FnMut()) -> Duration {
    (0..3)
        .map(|_| {
            let start = Instant::now();
            f();
            start.elapsed()
        })
        .min()
        .unwrap_or_default()
}

/// OZ01's "linear time": a million queries take about ten times as long
/// as a hundred thousand (the bound, 30, leaves room for a loaded
/// machine and is far below the hundredfold of a quadratic queue).
#[test]
fn a_flood_of_queries_is_answered_in_linear_time() {
    let unit = b"\x1b]4;1;?\x07";
    let run = |n: usize| {
        let bytes = unit.repeat(n);
        best_of_three(|| {
            let mut term = Terminal::new(24, 80);
            term.advance(&bytes);
            assert_eq!(term.take_requests().len(), n);
        })
    };
    let small = run(100_000);
    let large = run(1_000_000);
    eprintln!("OSC 4 queries x 100 000: {small:?}, x 1 000 000: {large:?}");
    assert!(
        large < small * 30,
        "1,000,000 queries took {large:?}, 100,000 took {small:?}"
    );
}

/// OZ02's bound: the overrides are one fixed table, whatever the input
/// (S5). A million sets with varying colours and indexes change its
/// contents, never its size.
#[test]
fn the_override_table_is_fixed_size() {
    assert_eq!(MAX_COLOR_OVERRIDES, 259);
    assert_eq!(ColorOverrides::NONE.palette.len() + 3, MAX_COLOR_OVERRIDES);
    let mut term = Terminal::new(24, 80);
    let mut bytes = Vec::new();
    for i in 0..1_000_000u32 {
        let [_, r, g, b] = i.to_be_bytes();
        bytes
            .extend_from_slice(format!("\x1b]4;{};#{r:02x}{g:02x}{b:02x}\x07", i % 256).as_bytes());
    }
    term.advance(&bytes);
    assert_eq!(term.take_requests(), []);
    let overrides = term.color_overrides();
    assert!(overrides.palette.iter().all(Option::is_some));
    assert_eq!(overrides.palette[63], Some(Rgb::new(0x0f, 0x42, 0x3f)));
    assert_eq!(
        std::mem::size_of::<ColorOverrides>(),
        4 * MAX_COLOR_OVERRIDES
    );
}

/// This process's resident set in KiB, from `ps` (no `unsafe` needed).
fn resident_kib() -> u64 {
    let out = std::process::Command::new("ps")
        .args(["-o", "rss=", "-p", &std::process::id().to_string()])
        .output()
        .expect("ps runs");
    String::from_utf8_lossy(&out.stdout)
        .trim()
        .parse()
        .expect("ps prints the resident set in KiB")
}

/// A flood of bogus colour names (S5, #187): `count` names of `len` bytes
/// of `a` (unknown, and longer than the 22-byte cap past 22) set nothing,
/// answer nothing and keep the resident set flat after a warm-up of the
/// same names: nothing is kept per name. Returns the growth in KiB.
fn flood_bogus_names(count: usize, len: usize) -> u64 {
    let mut unit = b"\x1b]11;".to_vec();
    unit.resize(unit.len() + len, b'a');
    unit.push(0x07);
    // About 1 MiB per read, as a busy PTY would deliver it.
    let per_read = (1 << 20) / unit.len() + 1;
    let read = unit.repeat(per_read);
    let mut term = Terminal::new(24, 80);
    term.set_theme_colors(theme_t());
    let generation = term.colors_generation();
    term.advance(&read);
    let before = resident_kib();
    for _ in 0..count.div_ceil(per_read) {
        term.advance(&read);
    }
    let after = resident_kib();
    term.advance(b"\x1b]11;red\x07");
    assert_eq!(term.take_requests(), [], "replies to bogus names");
    assert_eq!(
        term.colors().bg,
        Rgb::new(0xff, 0, 0),
        "the next set applies"
    );
    assert_eq!(
        term.colors_generation(),
        generation + 1,
        "only red moved it"
    );
    let grown = after.saturating_sub(before);
    eprintln!("{count} names of {len} bytes: resident {before} -> {after} KiB");
    grown
}

/// The names flood at the cap's edge and far past it: a million names of
/// 23 bytes (22 MiB) and two thousand of 64 KiB (128 MiB) grow the
