/// Repetitions of a generated row's step when it is not fed whole.
const CHUNKED_REPEAT: usize = 1_000;

/// Feed steps up to this long are split at every offset.
const SPLIT_ALL_UP_TO: usize = 4_096;

/// Offsets at each end of a longer feed step that it is split at.
const SPLIT_EDGE: usize = 64;

/// The header's TEST THEME T: `fg #d0d0d0 bg #101010 cursor #ffcc00`,
/// `palette[i] = (i, 255 - i, i ^ 0x55)`.
fn theme_t() -> ThemeColors {
    ThemeColors {
        fg: Rgb::new(0xd0, 0xd0, 0xd0),
        bg: Rgb::new(0x10, 0x10, 0x10),
        cursor: Rgb::new(0xff, 0xcc, 0x00),
        palette: std::array::from_fn(|i| {
            let i = u8::try_from(i).expect("index below 256");
            Rgb::new(i, 255 - i, i ^ 0x55)
        }),
    }
}

/// The header's TEST THEME T2: `fg #aabbcc bg #223344 cursor #00ff00`,
/// `palette[i] = (255 - i, i, i ^ 0xaa)`.
fn theme_t2() -> ThemeColors {
    ThemeColors {
        fg: Rgb::new(0xaa, 0xbb, 0xcc),
        bg: Rgb::new(0x22, 0x33, 0x44),
        cursor: Rgb::new(0x00, 0xff, 0x00),
        palette: std::array::from_fn(|i| {
            let i = u8::try_from(i).expect("index below 256");
            Rgb::new(255 - i, i, i ^ 0xaa)
        }),
    }
}

/// A colour key of `expect:` and `overrides:`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Key {
    Fg,
    Bg,
    Cursor,
    Pal(u8),
}

impl Key {
    fn parse(text: &str) -> Self {
        match text {
            "fg" => Self::Fg,
            "bg" => Self::Bg,
            "cursor" => Self::Cursor,
            _ => {
                let index = text
                    .strip_prefix("pal[")
                    .and_then(|t| t.strip_suffix(']'))
                    .and_then(|t| t.parse().ok())
                    .unwrap_or_else(|| panic!("unknown colour key `{text}`"));
                Self::Pal(index)
            }
        }
    }

    fn of(self, colors: &ThemeColors) -> Rgb {
        match self {
            Self::Fg => colors.fg,
            Self::Bg => colors.bg,
            Self::Cursor => colors.cursor,
            Self::Pal(i) => colors.palette[usize::from(i)],
        }
    }
}

/// The keys `overrides` has, in the fixture's order: fg, bg, cursor, then
/// the palette ascending.
fn override_keys(overrides: &ColorOverrides) -> Vec<Key> {
    let mut keys = Vec::new();
    for (key, slot) in [
        (Key::Fg, overrides.fg),
        (Key::Bg, overrides.bg),
        (Key::Cursor, overrides.cursor),
    ] {
        if slot.is_some() {
            keys.push(key);
        }
    }
    for (i, slot) in (0..=u8::MAX).zip(&overrides.palette) {
        if slot.is_some() {
            keys.push(Key::Pal(i));
        }
    }
    keys
}

/// One line of a row that does something, in fixture order.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Item {
    /// `step: feed`: the bytes, fed `repeat` times.
    Feed { bytes: Vec<u8>, repeat: usize },
    /// `step: set size`.
    Size(u16, u16),
    /// `step: set theme`: `true` for T2.
    Theme(bool),
    /// `reply:`: the expected reply bytes, `None` for `none`.
    Reply(Option<Vec<u8>>),
    /// `expect:`.
    Expect(Vec<(Key, Rgb)>),
    /// `overrides:`.
    Overrides(Vec<Key>),
    /// `gen:`: `true` for `+1`.
    Gen(bool),
    /// `requests:` (only `[]` in this fixture).
    Requests(Vec<Request>),
}

/// One row of the fixture.
#[derive(Debug, Clone)]
struct Row {
    id: String,
    rows: u16,
    cols: u16,
    items: Vec<Item>,
    screen: Option<String>,
    cursor: Option<Point>,
}

impl Row {
    fn generated(&self) -> bool {
        self.items
            .iter()
            .any(|item| matches!(item, Item::Feed { repeat, bytes } if *repeat > 1 || bytes.len() > SPLIT_ALL_UP_TO))
    }
}

/// Replaces the fixture's `\e` with `\x1b`, leaving `\\` alone, then
/// decodes the other escapes with [`common::decode`].
fn decode_payload(text: &str) -> Vec<u8> {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars();
    while let Some(ch) = chars.next() {
        if ch != '\\' {
            out.push(ch);
            continue;
        }
        match chars.next() {
            Some('e') => out.push_str("\\x1b"),
            Some(next) => {
                out.push('\\');
                out.push(next);
            }
            None => out.push('\\'),
        }
    }
    decode(&out)
}

fn parse_hex(text: &str) -> Rgb {
    let digits = text
        .strip_prefix('#')
        .filter(|d| d.len() == 6)
        .unwrap_or_else(|| panic!("colour `{text}`: expected #rrggbb"));
    let byte = |i: usize| u8::from_str_radix(&digits[i..i + 2], 16).expect("hex colour");
    Rgb::new(byte(0), byte(2), byte(4))
}

/// `step:` lines.
fn parse_step(text: &str) -> Item {
    if let Some(payload) = text.strip_prefix("feed ") {
        if let Some(count) = payload
            .strip_prefix("(OSC 11 ; then ")
            .and_then(|rest| rest.strip_suffix(" bytes of 'a', then BEL)"))
        {
            let count: usize = count.replace(',', "").parse().expect("byte count");
            let mut bytes = b"\x1b]11;".to_vec();
            bytes.resize(bytes.len() + count, b'a');
            bytes.push(0x07);
            return Item::Feed { bytes, repeat: 1 };
        }
        if let Some(rest) = payload.strip_prefix('(') {
            let (count, payload) = rest
                .split_once(" times) ")
                .unwrap_or_else(|| panic!("`feed {payload}`: expected `(N times) bytes`"));
            let repeat = count.replace(',', "").parse().expect("repeat count");
            return Item::Feed {
                bytes: decode_payload(payload),
                repeat,
            };
        }
        Item::Feed {
            bytes: decode_payload(payload),
            repeat: 1,
        }
    } else if let Some(size) = text.strip_prefix("set size ") {
        let (rows, cols) = size.trim().split_once('x').expect("size RxC");
        Item::Size(rows.parse().expect("rows"), cols.parse().expect("cols"))
    } else if let Some(theme) = text.strip_prefix("set theme ") {
        match theme.trim() {
            "T" => Item::Theme(false),
            "T2" => Item::Theme(true),
            other => panic!("unknown theme `{other}`"),
        }
    } else {
        panic!("unknown step `{text}`");
    }
}

fn parse_point(text: &str) -> Point {
    let (row, col) = text
        .trim()
        .strip_prefix('(')
        .and_then(|t| t.strip_suffix(')'))
        .and_then(|t| t.split_once(','))
        .unwrap_or_else(|| panic!("cursor `{text}`: expected `(row,col)`"));
    Point::new(row.parse().expect("row"), col.parse().expect("col"))
}

fn parse_row(id: String, lines: &[&str]) -> Row {
    let mut row = Row {
        id,
        rows: 0,
        cols: 0,
        items: Vec::new(),
        screen: None,
        cursor: None,
    };
    let mut lines = lines.iter().peekable();
    while let Some(line) = lines.next() {
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, value) = line
            .split_once(':')
            .unwrap_or_else(|| panic!("{}: unexpected line `{line}`", row.id));
        let value = value.strip_prefix(' ').unwrap_or(value);
        match key {
            "size" => {
                let (rows, cols) = value.trim().split_once('x').expect("size RxC");
                row.rows = rows.parse().expect("rows");
                row.cols = cols.parse().expect("cols");
            }
            "step" => row.items.push(parse_step(value)),
            "reply" => {
                let reply = (value.trim() != "none").then(|| {
                    decode_payload(&value.replace("<VERSION>", env!("CARGO_PKG_VERSION")))
                });
                row.items.push(Item::Reply(reply));
            }
            "expect" => row.items.push(Item::Expect(
                value
                    .split_whitespace()
                    .map(|pair| {
                        let (key, color) = pair.split_once('=').expect("k=#rrggbb");
                        (Key::parse(key), parse_hex(color))
                    })
                    .collect(),
            )),
            "overrides" => {
                let keys = if value.trim() == "none" {
                    Vec::new()
                } else {
                    value.split_whitespace().map(Key::parse).collect()
                };
                row.items.push(Item::Overrides(keys));
            }
            "gen" => row.items.push(Item::Gen(match value.trim() {
                "+1" => true,
                "same" => false,
                other => panic!("{}: gen `{other}`", row.id),
            })),
            "requests" => {
                assert_eq!(
                    value.trim(),
                    "[]",
                    "{}: only `requests: []` is read",
                    row.id
                );
                row.items.push(Item::Requests(Vec::new()));
            }
            "screen" => {
                let mut screen = String::new();
                while let Some(text) = lines.peek().and_then(|l| l.strip_prefix('>')) {
                    screen.push_str(text);
                    screen.push('\n');
                    lines.next();
                }
                row.screen = Some(screen);
            }
            "cursor" => row.cursor = Some(parse_point(value)),
            "cite" | "note" | "flags" => {}
            other => panic!("{}: unknown key `{other}`", row.id),
        }
    }
    assert!(row.rows > 0 && row.cols > 0, "{}: no size", row.id);
    row
}

fn rows(fixture: &str) -> Vec<Row> {
    let mut raw: Vec<(String, Vec<&str>)> = Vec::new();
    for line in fixture.lines() {
        if let Some(id) = line.strip_prefix("### ") {
            raw.push((id.trim().to_owned(), Vec::new()));
        } else if let Some((_, lines)) = raw.last_mut() {
            lines.push(line);
        }
    }
    raw.into_iter()
        .map(|(id, lines)| parse_row(id, &lines))
        .collect()
}

/// How a row's feed steps reach [`Terminal::advance`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Chunking {
    /// Each feed step in one call.
    Whole,
    /// One byte per call (the first repetition only for generated rows).
    Bytewise,
    /// Feed step `step` in two calls, split after `at` bytes of its first
    /// repetition; every other step whole.
    Split { step: usize, at: usize },
}

fn feed(term: &mut Terminal, bytes: &[u8], repeat: usize, index: usize, chunking: Chunking) {
    let mut first = bytes;
    match chunking {
        Chunking::Bytewise => {
            for byte in bytes {
                term.advance(std::slice::from_ref(byte));
            }
            first = &[];
        }
        Chunking::Split { step, at } if step == index => {
            term.advance(&bytes[..at]);
            first = &bytes[at..];
        }
        Chunking::Whole | Chunking::Split { .. } => {}
    }
    term.advance(first);
    if repeat > 1 {
        term.advance(&bytes.repeat(repeat - 1));
    }
}

/// Replies and other requests collected while running a row.
#[derive(Default)]
struct Collected {
    replies: Vec<Vec<u8>>,
    others: Vec<Request>,
}

impl Collected {
    fn take(&mut self, term: &mut Terminal) {
        for request in term.take_requests() {
            match request {
                Request::Reply(bytes) => self.replies.push(bytes),
                other => self.others.push(other),
            }
        }
    }
}

/// Runs `row` with `chunking` and returns one message per mismatch.
fn check_row(row: &Row, chunking: Chunking) -> Vec<String> {
    let mut errors = Vec::new();
    let mut fail = |what: String| errors.push(format!("{} [{chunking:?}]: {what}", row.id));
    let mut term = Terminal::new(row.rows, row.cols);
    term.set_theme_colors(theme_t());
    let mut generation = term.colors_generation();
    let mut got = Collected::default();
    for (index, item) in row.items.iter().enumerate() {
        match item {
            Item::Feed { bytes, repeat } => {
                let repeat = if chunking == Chunking::Whole {
                    *repeat
                } else {
                    (*repeat).min(CHUNKED_REPEAT)
                };
                feed(&mut term, bytes, repeat, index, chunking);
                got.take(&mut term);
            }
            Item::Size(rows, cols) => term.resize(*rows, *cols),
            Item::Theme(t2) => term.set_theme_colors(if *t2 { theme_t2() } else { theme_t() }),
            Item::Reply(want) => {
                let replies = std::mem::take(&mut got.replies);
                let concat = replies.concat();
                let ok = match want {
                    None => replies.is_empty(),
                    Some(want) => concat == *want,
                };
                if !ok {
                    fail(format!(
                        "reply {:?} != {:?}",
                        String::from_utf8_lossy(&concat),
                        want.as_deref().map(String::from_utf8_lossy)
                    ));
                }
            }
            Item::Expect(pairs) => {
                let colors = term.colors();
                for (key, want) in pairs {
                    let shown = key.of(&colors);
                    if shown != *want {
                        fail(format!("{key:?} is {shown:?}, want {want:?}"));
                    }
                }
            }
            Item::Overrides(want) => {
                let shown = override_keys(term.color_overrides());
                if shown != *want {
                    fail(format!("overrides {shown:?} != {want:?}"));
                }
            }
            Item::Gen(bumped) => {
                let now = term.colors_generation();
                if (now > generation) != *bumped || now < generation {
                    fail(format!(
                        "generation {generation} -> {now}, want {}",
                        if *bumped { "+1" } else { "same" }
                    ));
                }
                generation = now;
            }
            Item::Requests(want) => {
                let others = std::mem::take(&mut got.others);
                if others != *want {
                    fail(format!("requests {others:?} != {want:?}"));
                }
            }
        }
    }
    if let Some(screen) = &row.screen {
        let shown = render_screen(&term);
        if shown != *screen {
            fail(format!("screen\n{shown}!=\n{screen}"));
        }
    }
    if let Some(cursor) = row.cursor
        && term.grid().cursor() != cursor
    {
        fail(format!("cursor {:?} != {cursor:?}", term.grid().cursor()));
    }
    errors.extend(generated_extras(row, &got, chunking));
    errors
}

/// The checks the generated rows' notes describe beyond their keys.
fn generated_extras(row: &Row, got: &Collected, chunking: Chunking) -> Vec<String> {
    let mut errors = Vec::new();
    let id = row.id.split('_').next().unwrap_or_default();
    if id == "OZ01" {
        // One reply per query, every one the same as for one query.
        let n = got.replies.len();
        let want = if chunking == Chunking::Whole {
            1_000_000
        } else {
            CHUNKED_REPEAT
        };
        let reply = b"\x1b]4;1;rgb:0101/fefe/5454\x07";
        let all = got.replies.iter().all(|r| r == reply);
        if n != want || !all {
            errors.push(format!(
                "{id} [{chunking:?}]: {n} replies, all pal[1]: {all}"
            ));
        }
    }
    errors
}

/// Every chunking `row` runs with.
fn chunkings(row: &Row) -> Vec<Chunking> {
    let mut all = vec![Chunking::Whole, Chunking::Bytewise];
    for (step, item) in row.items.iter().enumerate() {
        if let Item::Feed { bytes, .. } = item {
            let len = bytes.len();
            if len <= SPLIT_ALL_UP_TO {
                all.extend((1..len).map(|at| Chunking::Split { step, at }));
            } else {
                let edges = (1..SPLIT_EDGE).chain(len - SPLIT_EDGE..len);
                all.extend(edges.map(|at| Chunking::Split { step, at }));
            }
        }
    }
    all
}

/// Every row of `fixture`, whole, byte by byte and at every two-way
/// split, through [`common::check_table`]: the rows run must be the
/// fixture's `###` rows (`want_rows` of them, `want_generated` generated).
fn check_fixture(name: &str, fixture: &str, want_rows: usize, want_generated: usize) {
    let rows = rows(fixture);
    let headings = fixture.lines().filter(|l| l.starts_with("### ")).count();
    assert_eq!(headings, want_rows, "rows in {name}");
    let generated: Vec<&str> = rows
        .iter()
        .filter(|row| row.generated())
        .map(|row| row.id.as_str())
        .collect();
    assert_eq!(
        generated.len(),
        want_generated,
        "generated rows: {generated:?}"
    );
    common::check_table(
        name,
        headings,
        rows.iter().map(|row| (row.id.clone(), row)),
        |row| {
            let errors: Vec<String> = chunkings(row)
                .into_iter()
                .flat_map(|chunking| check_row(row, chunking))
                .collect();
            // The first few say why; the count says how often.
            let shown: Vec<&str> = errors.iter().take(4).map(String::as_str).collect();
            assert!(
                errors.is_empty(),
                "{} mismatches, the first:\n{}",
                errors.len(),
                shown.join("\n")
            );
        },
    );
}

